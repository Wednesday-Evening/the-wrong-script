/* =====================================================================
   THE WRONG SCRIPT - arcade interface sound
   ---------------------------------------------------------------------
   The arcade's click is now generated by the shared room audio engine
   (assets/js/audio-engine.js), not by a recorded file. The supplied
   interface-click.mp3 has no established licence, so it is preserved on
   disk and not played.

   The toggle here is not a second, competing setting: it drives the
   engine's Effects channel, so this control and the floating controller's
   Effects slider always show the same state.
   ===================================================================== */

(function () {
  'use strict';

  var slot = document.querySelector('[data-sound-slot]');
  var audio = window.TWSAudio;

  if (!slot || !audio) { return; }

  var button = document.createElement('button');
  button.type = 'button';
  button.className = 'sound-toggle';
  button.setAttribute('aria-pressed', 'false');
  button.textContent = 'Interface sounds: off';
  slot.appendChild(button);

  var enabled = false;

  function render() {
    var level = audio.getLevel('effects');
    enabled = typeof level === 'number' && level > 0;
    button.setAttribute('aria-pressed', enabled ? 'true' : 'false');
    button.textContent = enabled
      ? 'Interface sounds: on'
      : 'Interface sounds: off';
  }

  function tick() {
    if (!enabled) { return; }
    audio.cue('clique');
  }

  button.addEventListener('click', function () {
    audio.setLevel('effects', enabled ? 0 : 80);
    render();
    if (enabled) { audio.cue('clique'); }
  });

  /* Arrow keys and WASD are the movement controls; they get the same quiet
     cue as a pressed button, throttled inside the engine. */
  document.addEventListener('keydown', function (event) {
    if (!enabled) { return; }
    if (event.altKey || event.ctrlKey || event.metaKey) { return; }
    var key = event.key;
    var movement = key === 'ArrowUp' || key === 'ArrowDown' ||
      key === 'ArrowLeft' || key === 'ArrowRight' ||
      key === 'w' || key === 'a' || key === 's' || key === 'd' ||
      key === 'W' || key === 'A' || key === 'S' || key === 'D';
    if (!movement) { return; }
    audio.cue('step');
  });

  /* Every button inside the game area gives the same subtle feedback, so a
     visitor can tell a press registered. */
  var main = document.getElementById('main') || document.body;
  main.addEventListener('click', function (event) {
    var target = event.target;
    if (!target || !target.closest) { return; }
    if (!target.closest('button')) { return; }
    tick();
  });

  window.addEventListener('tws:audio', render);
  window.addEventListener('pagehide', function () {
    enabled = false;
  });

  render();
})();
